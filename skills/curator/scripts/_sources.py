"""Transcripts of agent sessions, read into one shape whatever runtime wrote them.

Two runtimes keep transcripts on the machine, one JSON object per line:

- Claude Code under ``$CLAUDE_CONFIG_DIR/projects`` (default ``~/.claude/projects``): one directory per launch
  directory, its name the path with every character that is not a letter or a digit turned into ``-``; one
  ``<session>.jsonl`` per session and ``<session>/subagents/agent-<id>.jsonl`` per subagent it started. Lines of type
  ``assistant`` carry the model, its usage and ``tool_use`` items; lines of type ``user`` carry what the person wrote
  and the ``tool_result`` items (``is_error`` when a tool failed); ``system`` lines mark compactions
  (``compact_boundary``) and API errors; ``attachment`` lines record what was put into the context: the instruction
  files (``instructions``), the skill listing, MCP instructions, agent listing, deferred tool names, the system prompt.
- Codex under ``$CODEX_HOME/sessions`` and ``archived_sessions`` (default ``~/.codex``): ``YYYY/MM/DD/rollout-*.jsonl``,
  the first line a ``session_meta`` with the session's ``cwd``. Newer builds report each finished item as an
  ``event_msg`` of type ``item_completed`` (``CommandExecution`` with ``exit_code``, ``McpToolCall``, ``FileChange``,
  ``UserMessage``, ``ContextCompaction``); older ones only have ``response_item`` lines (``function_call`` and its
  ``function_call_output``) and ``exec_command_end`` events, read as a fallback. ``token_count`` events give the
  context size of each turn. A session imported from another runtime (turn ids ``external-import-turn-*``) is marked
  ``imported`` and left out by default: its original is counted where it was written.

Every call and turn keeps ``seq``, its line number in the file, so a figure can point back at the exact line
(``<runtime>:<session>:<seq>``). Standard library only.
"""

from __future__ import annotations

import json
import os
import re
import shlex
from collections import Counter
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path

RUNTIMES = ("claude", "codex")
KINDS = ("interactive", "headless", "subagent", "imported")
TEXT_CHARS = 600  # a user turn, as stored
ERROR_CHARS = 400  # the text of a failed tool result, as stored
SYNTHETIC_MODEL = "<synthetic>"
SKILL_PATH = re.compile(r"skills/([A-Za-z0-9][A-Za-z0-9_.:-]{0,99})/SKILL\.md")
COMMAND_NAME = re.compile(r"<command-name>\s*/?([^<\s]+)\s*</command-name>")
COMMAND_ARGS = re.compile(r"<command-args>(.*?)</command-args>", re.S)
INTERRUPTED = "[Request interrupted by user"
NOT_THE_PERSON = (
    "This session is being continued from a previous conversation",
    "Caveat: The messages below were generated by the user while running local commands",
)
PERSISTED = ("<persisted-output>", "Output too large")
READ_TOOLS = frozenset({"Read", "view_image"})
EDIT_TOOLS = frozenset({"Edit", "MultiEdit", "Write", "NotebookEdit", "apply_patch"})
SHELL_TOOLS = frozenset({"Bash", "shell"})
CODEX_SHELLS = frozenset({"shell", "exec_command", "local_shell", "container.exec", "shell_command"})
EXIT_CODE = re.compile(r"(?:Process exited with code|Exit code:?)\s*(-?\d+)")


@dataclass
class Call:
    """One tool call, and what came back."""

    seq: int
    tool: str
    command: str | None = None  # the shell command of a shell call
    path: str | None = None  # the file a read or edit tool touched
    skill: str | None = None  # the skill this call loaded
    subagent: str | None = None  # the agent type this call started
    failed: bool | None = None  # None: no result seen
    error: str | None = None
    output_chars: int = 0
    persisted: bool = False  # the result was too large and went to a file


@dataclass
class Turn:
    """What the person did in one turn: a prompt, a slash command, or an interrupt."""

    seq: int
    text: str
    kind: str = "prompt"  # prompt | command | interrupt


@dataclass
class Session:
    runtime: str
    id: str
    path: str
    cwd: str = ""
    kind: str = "interactive"
    parent: str | None = None
    agent_type: str | None = None
    started: str | None = None
    ended: str | None = None
    models: Counter = field(default_factory=Counter)
    turns: list[Turn] = field(default_factory=list)
    calls: list[Call] = field(default_factory=list)
    usage: Counter = field(default_factory=Counter)  # input, cache_write, cache_read, output, reasoning
    context: list[int] = field(default_factory=list)  # the context size of each model call, in order
    window: int | None = None
    compactions: list[int] = field(default_factory=list)  # seq of each compaction
    loaded: dict[str, int] = field(default_factory=dict)  # what the runtime put into the context: component, chars
    skill_listing: str | None = None
    mcp_servers: dict[str, int] = field(default_factory=dict)  # MCP server, chars of its instructions
    deferred_tools: list[str] = field(default_factory=list)
    attributed_skills: Counter = field(default_factory=Counter)
    api_errors: int = 0
    lines: int = 0

    @property
    def key(self) -> str:
        return f"{self.runtime}:{self.id}"


def cut(text, limit: int) -> str:
    text = str(text)
    return text if len(text) <= limit else text[: limit - 3] + "..."


def claude_home() -> Path:
    return Path(os.environ.get("CLAUDE_CONFIG_DIR") or "~/.claude").expanduser()


def codex_home() -> Path:
    return Path(os.environ.get("CODEX_HOME") or "~/.codex").expanduser()


def encode_path(path: str) -> str:
    """The directory name Claude Code gives the transcripts of sessions launched in ``path``."""
    return re.sub(r"[^A-Za-z0-9]", "-", path)


def in_scope(cwd: str, paths: list[str]) -> bool:
    if not cwd:
        return False
    cwd = cwd.rstrip("/") or "/"
    return any(cwd == p or cwd.startswith(p.rstrip("/") + "/") for p in paths)


def lines(path: Path | str) -> Iterator[tuple[int, dict]]:
    """Each JSON object of a transcript with its line number, from 1; broken lines are skipped."""
    with open(path, encoding="utf-8", errors="replace") as handle:
        for seq, raw in enumerate(handle, 1):
            raw = raw.strip()
            if not raw:
                continue
            try:
                value = json.loads(raw)
            except json.JSONDecodeError:
                continue
            if isinstance(value, dict):
                yield seq, value


def line_at(path: Path | str, seq: int) -> dict | None:
    for number, value in lines(path):
        if number == seq:
            return value
        if number > seq:
            break
    return None


def skill_of_path(text: str | None) -> str | None:
    found = SKILL_PATH.search(text or "")
    return found.group(1) if found else None


def _shell_text(command) -> str | None:
    """A shell command as one string: ``["/bin/zsh", "-lc", "ls"]`` is ``ls``."""
    if isinstance(command, str):
        return command
    if isinstance(command, list) and command:
        parts = [str(part) for part in command]
        if len(parts) >= 3 and parts[-2] in ("-c", "-lc", "-ic", "/c", "-Command"):
            return parts[-1]
        return shlex.join(parts)
    return None


# Claude Code


def _claude_result_text(item: dict) -> str:
    content = item.get("content", "")
    if isinstance(content, list):
        content = "\n".join(str(part.get("text", "")) for part in content if isinstance(part, dict))
    return str(content)


def _claude_call(seq: int, item: dict) -> Call:
    name = str(item.get("name") or "?")
    given = item.get("input") if isinstance(item.get("input"), dict) else {}
    call = Call(seq=seq, tool=name)
    if name == "Bash":
        call.command = str(given.get("command") or "")
        call.skill = skill_of_path(call.command)
    elif name in READ_TOOLS or name in EDIT_TOOLS:
        call.path = given.get("file_path") or given.get("notebook_path") or given.get("path")
        if name in READ_TOOLS:
            call.skill = skill_of_path(call.path)
    elif name == "Skill":
        skill = given.get("skill") or given.get("name") or given.get("command")
        call.skill = str(skill).lstrip("/") if skill else None
    elif name in ("Agent", "Task"):
        call.subagent = str(given.get("subagent_type") or "general-purpose")
    return call


def _claude_turn(seq: int, text: str) -> Turn | None:
    text = text.strip()
    if not text:
        return None
    if text.startswith(INTERRUPTED):
        return Turn(seq, "interrupted", "interrupt")
    name = COMMAND_NAME.search(text)
    if name:
        args = COMMAND_ARGS.search(text)
        shown = name.group(1) + (" " + args.group(1).strip() if args and args.group(1).strip() else "")
        return Turn(seq, cut(shown, TEXT_CHARS), "command")
    if text.startswith("<") or text.startswith(NOT_THE_PERSON):
        return None
    return Turn(seq, cut(text, TEXT_CHARS))


def _claude_attachment(session: Session, attachment: dict) -> None:
    kind = attachment.get("type")
    loaded = session.loaded
    if kind == "instructions":
        for item in attachment.get("files") or []:
            if isinstance(item, dict) and item.get("path"):
                key = f"instructions:{item.get('type') or 'file'}:{item['path']}"
                loaded[key] = max(loaded.get(key, 0), len(str(item.get("content") or "")))
    elif kind == "skill_listing":
        content = str(attachment.get("content") or "")
        if len(content) >= loaded.get("skill_listing", 0):
            loaded["skill_listing"] = len(content)
            session.skill_listing = content
    elif kind == "mcp_instructions_delta":
        names = attachment.get("addedNames") or []
        blocks = attachment.get("addedBlocks") or []
        for name, block in zip(names, blocks):
            session.mcp_servers[str(name)] = len(str(block))
        loaded["mcp_instructions"] = sum(session.mcp_servers.values())
    elif kind == "agent_listing_delta":
        added = sum(len(str(line)) for line in attachment.get("addedLines") or [])
        loaded["agent_listing"] = loaded.get("agent_listing", 0) + added
    elif kind == "deferred_tools_delta":
        names = [str(name) for name in attachment.get("addedNames") or []]
        session.deferred_tools.extend(names)
        loaded["deferred_tool_names"] = sum(len(name) for name in session.deferred_tools)
    elif kind == "prompt_snapshot":
        parts = attachment.get("systemPrompt") or []
        size = sum(len(str(part)) for part in parts) if isinstance(parts, list) else len(str(parts))
        loaded["system_prompt"] = max(loaded.get("system_prompt", 0), size)
    elif kind == "hook_additional_context":
        content = attachment.get("content") or []
        size = sum(len(str(part)) for part in content) if isinstance(content, list) else len(str(content))
        loaded["hook_context"] = loaded.get("hook_context", 0) + size


def read_claude(path: Path, parent: str | None = None) -> Session:
    """The session of one Claude Code transcript; ``parent`` names the session a subagent transcript belongs to."""
    session = Session(runtime="claude", id=path.stem, path=str(path))
    if parent:
        session.kind = "subagent"
        session.parent = parent
        session.id = f"{parent}/{path.stem}"
        meta = path.with_name(path.stem + ".meta.json")
        if meta.is_file():
            try:
                session.agent_type = json.loads(meta.read_text(encoding="utf-8")).get("agentType")
            except (OSError, ValueError, AttributeError):
                pass
    pending: dict[str, Call] = {}
    seen: set = set()
    for seq, line in lines(path):
        session.lines = seq
        kind = line.get("type")
        if not session.cwd and line.get("cwd"):
            session.cwd = str(line["cwd"])
        stamp = line.get("timestamp")
        if isinstance(stamp, str):
            session.started = session.started or stamp
            session.ended = stamp
        entry = line.get("entrypoint")
        if session.kind == "interactive" and isinstance(entry, str) and entry.startswith("sdk"):
            session.kind = "headless"
        message = line.get("message") if isinstance(line.get("message"), dict) else {}
        if kind == "assistant":
            ident = message.get("id") or line.get("requestId") or f"line-{seq}"
            if ident not in seen:
                seen.add(ident)
                model = message.get("model")
                if model and model != SYNTHETIC_MODEL:
                    session.models[str(model)] += 1
                usage = message.get("usage") if isinstance(message.get("usage"), dict) else {}
                if usage:
                    fresh = int(usage.get("input_tokens") or 0)
                    write = int(usage.get("cache_creation_input_tokens") or 0)
                    read = int(usage.get("cache_read_input_tokens") or 0)
                    session.usage.update(
                        input=fresh, cache_write=write, cache_read=read, output=int(usage.get("output_tokens") or 0)
                    )
                    if fresh + write + read:
                        session.context.append(fresh + write + read)
                if line.get("attributionSkill"):
                    session.attributed_skills[str(line["attributionSkill"])] += 1
            for item in message.get("content") or []:
                if isinstance(item, dict) and item.get("type") == "tool_use":
                    call = _claude_call(seq, item)
                    session.calls.append(call)
                    if item.get("id"):
                        pending[str(item["id"])] = call
        elif kind == "user":
            if line.get("isCompactSummary"):
                continue
            content = message.get("content")
            texts: list[str] = []
            if isinstance(content, str):
                texts.append(content)
            for item in content if isinstance(content, list) else []:
                if not isinstance(item, dict):
                    continue
                if item.get("type") == "tool_result":
                    call = pending.pop(str(item.get("tool_use_id")), None)
                    if call is None:
                        continue
                    text = _claude_result_text(item)
                    call.failed = bool(item.get("is_error"))
                    call.output_chars = len(text)
                    call.persisted = any(mark in text[:200] for mark in PERSISTED)
                    if call.failed:
                        call.error = cut(text.strip(), ERROR_CHARS)
                elif item.get("type") == "text":
                    texts.append(str(item.get("text") or ""))
            if session.kind != "subagent" and not line.get("isMeta"):
                for text in texts:
                    turn = _claude_turn(seq, text)
                    if turn:
                        session.turns.append(turn)
        elif kind == "system":
            subtype = line.get("subtype")
            if subtype == "compact_boundary":
                session.compactions.append(seq)
            elif subtype == "api_error":
                session.api_errors += 1
        elif kind == "attachment" and isinstance(line.get("attachment"), dict):
            _claude_attachment(session, line["attachment"])
    return session


def find_claude(paths: list[str], since: float) -> Iterator[tuple[Path, str | None]]:
    """Transcript files, and the parent session of a subagent's, whose directory may hold sessions of ``paths``,
    written since ``since``. The directory name is only a first filter: the cwd inside decides."""
    root = claude_home() / "projects"
    if not root.is_dir():
        return
    prefixes = [encode_path(p.rstrip("/")) for p in paths]
    for directory in sorted(root.iterdir()):
        if not directory.is_dir() or not any(directory.name.startswith(prefix) for prefix in prefixes):
            continue
        for path in sorted(directory.glob("*.jsonl")):
            if _mtime(path) >= since:
                yield path, None
        for path in sorted(directory.glob("*/subagents/*.jsonl")):
            if _mtime(path) >= since:
                yield path, path.parent.parent.name


# Codex


def _codex_text(content) -> str:
    if isinstance(content, str):
        return content
    parts = []
    for item in content if isinstance(content, list) else []:
        if isinstance(item, dict) and isinstance(item.get("text"), str):
            parts.append(item["text"])
    return "\n".join(parts)


def _codex_item(session: Session, seq: int, item: dict, calls: list[Call], turns: list[Turn]) -> None:
    kind = item.get("type")
    status = item.get("status")
    if kind == "UserMessage":
        turn = _claude_turn(seq, _codex_text(item.get("content")))
        if turn:
            turns.append(turn)
    elif kind == "CommandExecution":
        command = _shell_text(item.get("command")) or ""
        output = str(item.get("aggregated_output") or item.get("formatted_output") or "")
        code = item.get("exit_code")
        call = Call(seq=seq, tool="shell", command=command, skill=skill_of_path(command), output_chars=len(output))
        call.failed = status == "failed" or (isinstance(code, int) and code != 0)
        for parsed in item.get("parsed_cmd") or []:
            if isinstance(parsed, dict) and parsed.get("type") == "read" and parsed.get("path"):
                call.path = str(parsed["path"])
                break
        if call.failed:
            call.error = cut((output.strip() or f"exit code {code}"), ERROR_CHARS)
        calls.append(call)
    elif kind == "McpToolCall":
        result = item.get("result") if isinstance(item.get("result"), dict) else {}
        call = Call(seq=seq, tool=f"mcp__{item.get('server')}__{item.get('tool')}")
        text = _codex_text(result.get("content"))
        call.output_chars = len(text)
        call.failed = status == "failed" or bool(result.get("isError")) or bool(item.get("error"))
        if call.failed:
            call.error = cut(str(item.get("error") or text).strip(), ERROR_CHARS)
        calls.append(call)
    elif kind == "FileChange":
        changes = item.get("changes") if isinstance(item.get("changes"), dict) else {}
        for path in list(changes)[:1] or [None]:
            calls.append(Call(seq=seq, tool="apply_patch", path=path, failed=status == "failed"))
    elif kind == "ImageView":
        calls.append(Call(seq=seq, tool="view_image", path=str(item.get("path") or "").removeprefix("file://")))
    elif kind == "Extension":
        calls.append(Call(seq=seq, tool=str(item.get("kind") or "extension"), failed=status == "failed"))
    elif kind == "CollabAgentToolCall":
        tool = str(item.get("tool") or "agent")
        call = Call(seq=seq, tool=f"agent.{tool}", failed=status == "failed")
        if tool == "spawn_agent":
            call.subagent = str(item.get("agent_type") or "spawned")
        calls.append(call)
    elif kind == "ContextCompaction":
        session.compactions.append(seq)


def read_codex(path: Path) -> Session:
    """The session of one Codex rollout file."""
    session = Session(runtime="codex", id=path.stem.removeprefix("rollout-"), path=str(path))
    item_calls: list[Call] = []
    item_turns: list[Turn] = []
    fallback_calls: list[Call] = []
    fallback_turns: list[Turn] = []
    fallback_compactions: list[int] = []
    pending: dict[str, Call] = {}
    has_items = False
    for seq, line in lines(path):
        session.lines = seq
        kind = line.get("type")
        payload = line.get("payload") if isinstance(line.get("payload"), dict) else {}
        stamp = line.get("timestamp")
        if isinstance(stamp, str):
            session.started = session.started or stamp
            session.ended = stamp
        turn_id = payload.get("turn_id")
        if isinstance(turn_id, str) and turn_id.startswith("external-import-turn"):
            session.kind = "imported"
        if kind == "session_meta":
            session.id = str(payload.get("id") or session.id)
            session.cwd = str(payload.get("cwd") or session.cwd)
            source = payload.get("source")
            originator = str(payload.get("originator") or "")
            if isinstance(source, dict) and "subagent" in source:
                session.kind = "subagent"
                spawn = source["subagent"].get("thread_spawn") if isinstance(source["subagent"], dict) else None
                if isinstance(spawn, dict):
                    session.parent = spawn.get("parent_thread_id")
                    session.agent_type = spawn.get("agent_type") or spawn.get("agent_role")
            elif source == "exec" or originator in ("codex_exec", "codex_python_sdk") or "sdk" in originator:
                session.kind = "headless"
        elif kind == "turn_context":
            if payload.get("model"):
                session.models[str(payload["model"])] += 1
            if not session.cwd and payload.get("cwd"):
                session.cwd = str(payload["cwd"])
        elif kind == "compacted":
            fallback_compactions.append(seq)
        elif kind == "event_msg":
            event = payload.get("type")
            if event == "item_completed" and isinstance(payload.get("item"), dict):
                has_items = True
                _codex_item(session, seq, payload["item"], item_calls, item_turns)
            elif event == "token_count" and isinstance(payload.get("info"), dict):
                info = payload["info"]
                last = info.get("last_token_usage") if isinstance(info.get("last_token_usage"), dict) else {}
                if int(last.get("input_tokens") or 0) > 0:
                    session.context.append(int(last["input_tokens"]))
                total = info.get("total_token_usage") if isinstance(info.get("total_token_usage"), dict) else {}
                if total:
                    cached = int(total.get("cached_input_tokens") or 0)
                    session.usage = Counter(
                        input=max(int(total.get("input_tokens") or 0) - cached, 0),
                        cache_read=cached,
                        cache_write=int(total.get("cache_write_input_tokens") or 0),
                        output=int(total.get("output_tokens") or 0),
                        reasoning=int(total.get("reasoning_output_tokens") or 0),
                    )
                if info.get("model_context_window"):
                    session.window = int(info["model_context_window"])
            elif event == "turn_aborted" and payload.get("reason") == "interrupted":
                item_turns.append(Turn(seq, "interrupted", "interrupt"))
                fallback_turns.append(Turn(seq, "interrupted", "interrupt"))
            elif event == "user_message":
                turn = _claude_turn(seq, str(payload.get("message") or ""))
                if turn:
                    fallback_turns.append(turn)
            elif event == "exec_command_end":
                call = pending.get(str(payload.get("call_id")))
                if call is not None:
                    code = payload.get("exit_code")
                    output = str(payload.get("aggregated_output") or payload.get("stdout") or "")
                    call.output_chars = len(output)
                    call.failed = isinstance(code, int) and code != 0
                    call.error = cut(output.strip() or f"exit code {code}", ERROR_CHARS) if call.failed else None
            elif event == "thread_settings_applied":
                settings = payload.get("thread_settings") if isinstance(payload.get("thread_settings"), dict) else {}
                if settings.get("model"):
                    session.models[str(settings["model"])] += 1
        elif kind == "response_item":
            _codex_response_item(seq, payload, fallback_calls, pending)
    session.calls = item_calls if has_items else fallback_calls
    session.turns = item_turns if has_items else fallback_turns
    if not has_items:
        session.compactions = fallback_compactions
    if session.kind == "subagent":
        session.turns = []
    return session


def _codex_response_item(seq: int, payload: dict, calls: list[Call], pending: dict[str, Call]) -> None:
    kind = payload.get("type")
    if kind in ("function_call", "custom_tool_call", "local_shell_call"):
        name = str(payload.get("name") or ("local_shell" if kind == "local_shell_call" else "?"))
        if payload.get("namespace"):
            name = f"{payload['namespace']}.{name}"
        call = Call(seq=seq, tool=name)
        given = payload.get("arguments")
        if isinstance(given, str):
            try:
                given = json.loads(given)
            except ValueError:
                given = {}
        if kind == "local_shell_call":
            given = payload.get("action") if isinstance(payload.get("action"), dict) else {}
        if name in CODEX_SHELLS and isinstance(given, dict):
            call.tool = "shell"
            call.command = _shell_text(given.get("command") or given.get("cmd")) or ""
            call.skill = skill_of_path(call.command)
        calls.append(call)
        if payload.get("call_id"):
            pending[str(payload["call_id"])] = call
    elif kind in ("function_call_output", "custom_tool_call_output"):
        call = pending.get(str(payload.get("call_id")))
        if call is None:
            return
        output = payload.get("output")
        text = output if isinstance(output, str) else _codex_text(output)
        code = None
        try:
            parsed = json.loads(text)
            if isinstance(parsed, dict):
                meta = parsed.get("metadata") if isinstance(parsed.get("metadata"), dict) else {}
                code = meta.get("exit_code")
                text = str(parsed.get("output", text))
        except (ValueError, TypeError):
            found = EXIT_CODE.search(text or "")
            code = int(found.group(1)) if found else None
        call.output_chars = len(text or "")
        if isinstance(code, int):
            call.failed = code != 0
            call.error = cut((text or "").strip() or f"exit code {code}", ERROR_CHARS) if call.failed else None


def codex_meta(path: Path) -> dict:
    """The ``session_meta`` payload of a rollout file, from its first lines, or {}."""
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            for _ in range(5):
                raw = handle.readline()
                if not raw:
                    break
                try:
                    value = json.loads(raw)
                except ValueError:
                    continue
                if isinstance(value, dict) and value.get("type") == "session_meta":
                    return value.get("payload") if isinstance(value.get("payload"), dict) else {}
    except OSError:
        pass
    return {}


def find_codex(paths: list[str], since: float) -> Iterator[Path]:
    """Rollout files written since ``since`` whose session ran in one of ``paths``."""
    home = codex_home()
    for folder in (home / "sessions", home / "archived_sessions"):
        if not folder.is_dir():
            continue
        for path in sorted(folder.rglob("rollout-*.jsonl")):
            if _mtime(path) >= since and in_scope(str(codex_meta(path).get("cwd") or ""), paths):
                yield path


def _mtime(path: Path) -> float:
    try:
        return path.stat().st_mtime
    except OSError:
        return 0.0


def load(paths: list[str], since: float, runtimes=RUNTIMES, imported: bool = False) -> tuple[list[Session], Counter]:
    """Sessions of ``paths`` written since ``since``, and a count of those skipped by reason."""
    sessions: list[Session] = []
    skipped: Counter = Counter()
    if "claude" in runtimes:
        for path, parent in find_claude(paths, since):
            session = read_claude(path, parent)
            if not in_scope(session.cwd, paths):
                if parent is None and session.cwd:
                    skipped["claude:out_of_scope"] += 1
                continue
            sessions.append(session)
    if "codex" in runtimes:
        for path in find_codex(paths, since):
            session = read_codex(path)
            if session.kind == "imported" and not imported:
                skipped["codex:imported"] += 1
                continue
            sessions.append(session)
    # A subagent's transcript is read on its own, but it belongs to the scope of its parent.
    known = {s.id for s in sessions if s.kind != "subagent"}
    kept = [s for s in sessions if s.kind != "subagent" or s.runtime == "codex" or (s.parent in known)]
    skipped["claude:orphan_subagent"] += len(sessions) - len(kept)
    return kept, +skipped
